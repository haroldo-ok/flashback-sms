static void load_tile_direct(unsigned char tile_num, const unsigned char *src) {
    unsigned char i;
    SMS_setAddr(0x4000 | ((unsigned int)tile_num * 32));
    for (i = 0; i < 32; i++) {
        SMS_VDPDataPort = src[i];
    }
}

